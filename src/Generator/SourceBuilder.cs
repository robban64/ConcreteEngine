using System.Text;

namespace Generator;


internal sealed class SourceBuilder
{
    private const string IndentUnit = "    ";

    private int _indent;

    private readonly StringBuilder _sb = new(1024);

    public void PushIndent() => _indent++;
    public void PopIndent() => _indent--;

    public SourceBuilder AppendLine(string line = "")
    {
        if (line.Length == 0)
        {
            _sb.AppendLine();
            return this;
        }

        for (var i = 0; i < _indent; i++) _sb.Append(IndentUnit);

        _sb.AppendLine(line);
        return this;
    }
    public SourceBuilder AppendIndent()
    {
        for (var i = 0; i < _indent; i++) _sb.Append(IndentUnit);
        return this;
    }

    public SourceBuilder Append(string text)
    {
        _sb.Append(text);
        return this;
    }
    public SourceBuilder Append(int v)
    {
        _sb.Append(v);
        return this;
    }
    public SourceBuilder Append(float v)
    {
        _sb.Append(v);
        return this;
    }

    public SourceBuilder OpenBrace()
    {
        AppendLine("{");
        _indent++;
        return this;
    }

    public SourceBuilder CloseBrace(string suffix = "")
    {
        _indent--;
        AppendLine("}" + suffix);
        return this;
    }

    public BlockScope Block(string header)
    {
        AppendLine(header);
        return new BlockScope(this);
    }

    public readonly struct BlockScope : IDisposable
    {
        private readonly SourceBuilder _owner;
        public BlockScope(SourceBuilder owner) { _owner = owner; _owner.OpenBrace(); }
        public void Dispose() => _owner.CloseBrace();
    }

    public SourceBuilder AutoGeneratedHeader(string generatorName)
    {
        AppendLine("// <auto-generated/>");
        AppendLine($"// Generator: {generatorName}");
        AppendLine("// Do NOT edit – changes will be overwritten on next build.");
        AppendLine("#nullable enable");
        AppendLine();
        return this;
    }

    public override string ToString() => _sb.ToString();
}
