using System.Diagnostics.CodeAnalysis;
using System.Text;

namespace Generator;

internal ref struct SourceBuilder
{
    private const string IndentUnit = "    ";

    private readonly StringBuilder _sb;

    private int _indent;

    public SourceBuilder(int capacity)
    {
        _indent = 0;
        _sb = new StringBuilder(capacity);
    }
    public SourceBuilder()
    {
        _indent = 0;
        _sb = new StringBuilder(4096);
    }


    public void PushIndent() => _indent++;
    public void PopIndent() => _indent--;
    public StringBuilder Builder => _sb;

    [UnscopedRef]
    public ref SourceBuilder AppendLine(string line = "")
    {
        if (line.Length == 0)
        {
            _sb.AppendLine();
            return ref this;
        }

        for (var i = 0; i < _indent; i++) _sb.Append(IndentUnit);

        _sb.AppendLine(line);
        return ref this;
    }
    
    [UnscopedRef]
    public ref SourceBuilder AppendIndent(string line = "")
    {
        for (var i = 0; i < _indent; i++) _sb.Append(IndentUnit);
        _sb.Append(line);
        return ref this;
    }

    [UnscopedRef]
    public ref SourceBuilder Append(string text)
    {
        _sb.Append(text);
        return ref this;
    }
    
    [UnscopedRef]
    public ref SourceBuilder Append(int v)
    {
        _sb.Append(v);
        return ref this;
    }
    
    [UnscopedRef]
    public ref SourceBuilder Append(float v)
    {
        _sb.Append(v);
        return ref this;
    }

    [UnscopedRef]
    public ref SourceBuilder OpenBrace()
    {
        AppendLine("{");
        _indent++;
        return ref this;
    }

    [UnscopedRef]
    public ref SourceBuilder CloseBrace(string suffix = "")
    {
        _indent--;
        AppendLine("}" + suffix);
        return ref this;
    }

    public BlockScope Block(string header)
    {
        AppendLine(header);
        return new BlockScope(this);
    }

    public ref struct BlockScope : IDisposable
    {
        private SourceBuilder _owner;
        public BlockScope(SourceBuilder owner) { _owner = owner; _owner.OpenBrace(); }
        public void Dispose() => _owner.CloseBrace();
    }

    [UnscopedRef]
    public ref SourceBuilder AutoGeneratedHeader(string generatorName)
    {
        AppendLine("// <auto-generated/>");
        AppendLine($"// Generator: {generatorName}");
        AppendLine("// Do NOT edit – changes will be overwritten on next build.");
        AppendLine("#nullable enable");
        AppendLine();
        return ref this;
    }

    public override string ToString() => _sb.ToString();
}
